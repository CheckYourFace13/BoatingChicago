/**
 * Writes build SHA for /api/deploy-info.
 * Safe when .git is missing (e.g. some hosts).
 */
const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");

let sha = "unknown";
try {
  sha = execSync("git rev-parse HEAD", { encoding: "utf8" }).trim();
} catch {
  // leave unknown
}

const dir = path.join(__dirname, "..", "src", "generated");
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(
  path.join(dir, "build-info.ts"),
  `/** Auto-generated by scripts/write-build-sha.js — do not edit */\nexport const BUILD_SHA = ${JSON.stringify(sha)};\n`,
  "utf8"
);

console.log(`[prebuild] BUILD_SHA=${sha}`);
